D2R      = pi/180;     % deg to rad
R2D      = 180/pi;     % rad to deg
MS2KNOTS = 3600/1852;  % m/s to knots (1 knot = 1852 m/h)
KNOTS2MS = 1852/3600;  % knots to m/s
